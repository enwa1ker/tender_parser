# ── Исключения — если есть эти слова, тендер НЕ релевантен ──────────────────
EXCLUDE_KEYWORDS = [
    "электронн торг",       # электронные торги — платформа
    "электронн аукцион",    # электронный аукцион как платформа
    "электронн документ",   # электронный документооборот
    "электронн правительств",
    "электронн услуг",
    "электронн портал",
    "e-commerce",
    "интернет-магазин",
    "программное обеспечени",  # ПО без связи с электрикой
    "мобильн приложени",
]


def is_relevant(title: str) -> bool:
    """
    Возвращает True если тендер релевантен.
    Поиск регистронезависимый — работает с любым регистром букв.
    """
    if not title:
        return False

    # Приводим к нижнему регистру — решает проблему с КАПСЛОКОМ
    title_lower = title.lower()

    # Убираем лишние пробелы
    title_lower = re.sub(r'\s+', ' ', title_lower).strip()

    # Сначала исключения
    for excl in EXCLUDE_KEYWORDS:
        if excl in title_lower:
            return False

    # Затем ключевые слова
    for kw in KEYWORDS:
        if kw in title_lower:
            return True

    return False


