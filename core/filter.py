# Слова-исключения: если заголовок содержит их — пропускаем
# (чтобы не хватать нерелевантные тендеры со словом "электр" в имени компании)
EXCLUDE_KEYWORDS = [
    "электронн",       # электронные услуги, ПО и т.п. — не наш профиль
    "электронная торговл",
    "e-commerce",
]


def is_relevant(title: str) -> bool:
    """
    Возвращает True если заголовок тендера содержит хотя бы одно ключевое слово
    и не содержит слов-исключений.
    """
    if not title:
        return False

    title_lower = title.lower()

    # Сначала проверяем исключения
    for excl in EXCLUDE_KEYWORDS:
        if excl in title_lower:
            return False

    # Потом ключевые слова
    for kw in KEYWORDS:
        if kw in title_lower:
            return True

    return False
