    """Тест фильтра — запусти python3 -c 'from core.filter import test_filter; test_filter()'"""
    tests = [
        # (заголовок, ожидаемый результат)
        ("ЗАПРОС КОТИРОВОК НА ПОСТАВКУ ЭЛЕКТРОТЕХНИЧЕСКИХ ТОВАРОВ", True),
        ("Поставка кабельной продукции", True),
        ("Строительство ЛЭП 110 кВ", True),
        ("Монтаж КТП-630 кВА", True),
        ("Проектирование подстанции 35/10 кВ", True),
        ("Поставка светодиодных светильников", True),
        ("АСУТП для насосной станции", True),
        ("Видеонаблюдение на объекте", True),
        ("Жарык берүү системасы", True),           # кыргызский
        ("Поставка продуктов питания", False),
        ("Ремонт автодороги", False),
        ("Электронный аукцион на поставку мебели", False),
        ("Закупка компьютеров и ПО", False),
    ]

    print("\n=== Тест фильтра ===")
    ok = 0
    fail = 0
    for title, expected in tests:
        result = is_relevant(title)
        status = "✅" if result == expected else "❌"
        if result == expected:
            ok += 1
        else:
            fail += 1
        print(f"{status} [{'+' if result else '-'}] {title[:60]}")

    print(f"\nРезультат: {ok}/{len(tests)} прошло, {fail} ошибок\n")
